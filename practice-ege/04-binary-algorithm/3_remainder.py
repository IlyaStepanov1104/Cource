# Задание ФИПИ AB1E4C.
# По числу N строим R: берём двоичную запись N.
# Если N делится на 3 - дописываем в конец три последние двоичные цифры.
# Иначе остаток от деления на 3 умножаем на 3, переводим в двоичную и дописываем в конец.
def build_r(n: int) -> int:
    s = bin(n)[2:]
    if n % 3 == 0:
        s = s + s[-3:]
    else:
        s = s + bin(n % 3 * 3)[2:]
    return int(s, 2)


# Минимальное N, при котором R не меньше 76.
def answer() -> int:
    for n in range(1, 1000):
        if build_r(n) >= 76:
            return n




print(build_r(12), 100)
print(build_r(4), 19)
print(answer(), 11)
