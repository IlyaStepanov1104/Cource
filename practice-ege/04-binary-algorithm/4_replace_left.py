# По числу N строим R: берём двоичную запись N.
# Если сумма её цифр чётная - справа дописываем 0, затем два левых разряда заменяем на 10.
# Если нечётная - справа дописываем 1, затем два левых разряда заменяем на 11.
def build_r(n: int) -> int:
    s = bin(n)[2:]
    if s.count('1') % 2 == 0:
        s = '10' + (s + '0')[2:]
    else:
        s = '11' + (s + '1')[2:]
    return int(s, 2)

# Минимальное N, при котором R больше 29.
def answer() -> int:
    for n in range(1, 1000):
        if build_r(n) > 29:
            return n


print(build_r(6), 8)
print(build_r(4), 13)
print(answer(), 11)
