# По числу N строим R: берём двоичную запись N.
# Если N чётное - дописываем по две единицы справа и слева.
# Если N нечётное - справа дописываем два нуля, слева единицу.
# Полученная запись - двоичная запись R.
def build_r(n: int) -> int:
    s = bin(n)[2:]
    if n % 2 == 0:
        s = '11' + s + '11'
    else:
        s = '1' + s + '00'
    return int(s, 2)


# Наименьшее R, превышающее 95, которое может получиться.
def answer():
    best = float('inf')
    for n in range(1, 1000):
        r = build_r(n)
        if r > 95 and r < best:
            best = r
    return best




print(build_r(13), 116)
print(build_r(6), 123)
print(answer(), 100)
