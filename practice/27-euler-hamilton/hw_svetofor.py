"""
Разбор ДЗ прошлого занятия: acmp 124 "Светофорчики"
https://acmp.ru/index.asp?main=task&id_task=124

В подземелье M тоннелей соединяют N перекрёстков. Перед каждым перекрёстком
в каждом тоннеле стоит светофор. Нужно вывести, сколько светофоров стоит
у каждого перекрёстка - по порядку от 1 до N.

adj = {1: [2, 3], ...} - список смежности (словарь), вершины нумеруются с 1.

Ответ - количество светофоров у перекрёстка i это просто его степень:
len(adj[i]). Отдельный алгоритм не нужен - вся задача про степени вершин.
"""


def traffic_lights(adj: dict) -> list:
    n = len(adj)
    return [len(adj[i]) for i in range(1, n + 1)]


# ---- проверка: слева результат функции, справа ожидаемое ----

# 3 перекрёстка, тоннели: 1-2, 2-3
g1 = {1: [2], 2: [1, 3], 3: [2]}
print(traffic_lights(g1), [1, 2, 1])

# 4 перекрёстка, тоннели: 1-2, 1-3, 1-4, 2-3
g2 = {1: [2, 3, 4], 2: [1, 3], 3: [1, 2], 4: [1]}
print(traffic_lights(g2), [3, 2, 2, 1])

# перекрёсток без тоннелей - светофоров у него 0
g3 = {1: [2], 2: [1], 3: []}
print(traffic_lights(g3), [1, 1, 0])


# ---- формат ввода-вывода acmp: первая строка N и M, дальше M пар вершин ----
# для сдачи на acmp вызвать read_and_solve() вручную - здесь не запускаем,
# чтобы файл спокойно прогонялся без реального стандартного ввода

def read_and_solve():
    n, m = map(int, input().split())
    adj = {i: [] for i in range(1, n + 1)}
    for _ in range(m):
        u, v = map(int, input().split())
        adj[u].append(v)
        adj[v].append(u)
    print(*traffic_lights(adj))
