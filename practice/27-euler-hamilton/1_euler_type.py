"""
Задача: по списку смежности неориентированного графа определить,
какой обход существует - эйлеров цикл, эйлеров путь или ничего.

adj = {0: [1, 2], 1: [0, 2], ...} - список смежности (словарь),
рёбра неориентированные и хранятся в обе стороны (если 1 есть в adj[0],
то и 0 есть в adj[1]).

Вернуть одну из строк: "cycle", "path", "none".

Критерий:
- граф связен (среди вершин с ненулевой степенью) и все степени чётные -> "cycle"
- граф связен и ровно 2 вершины нечётной степени -> "path"
- иначе -> "none"

Изолированные вершины (степень 0) в проверку связности не включаем -
они не мешают обходу, если в графе вообще есть рёбра.
"""


def euler_type(adj: dict) -> str:
    visited = set()
    count = 0
    odd = 0

    def dfs(v):
        visited.add(v)
        for to in adj[v]:
            if to not in visited:
                dfs(to)

    for i in adj:
        if len(adj[i]) % 2 == 1:
            odd += 1
        if i not in visited and adj[i]:
            count += 1
            dfs(i)

    if count > 1:
        return "none"

    if odd == 0:
        return 'cycle'
    elif odd == 2:
        return 'path'
    else:
        return 'none'



# ---- проверка: слева результат функции, справа ожидаемое ----

# квадрат - простой цикл, все степени чётные
square = {0: [1, 3], 1: [0, 2], 2: [1, 3], 3: [2, 0]}
print(euler_type(square), "cycle")

# треугольник + хвост (пример со слайда) - ровно 2 нечётные вершины
tri_tail = {1: [2, 3], 2: [3, 1], 3: [1, 2, 4], 4: [3]}
print(euler_type(tri_tail), "path")

# мосты Кёнигсберга: все 4 вершины нечётной степени - обхода нет
konigsberg = {
    "N": ["A", "A", "B"],
    "S": ["A", "A", "B"],
    "A": ["N", "N", "S", "S", "B"],
    "B": ["N", "S", "A"],
}
print(euler_type(konigsberg), "none")

# граф-бабочка (два треугольника с общей вершиной) - все степени чётные
bowtie = {
    "A": ["B", "C"],
    "B": ["A", "C"],
    "C": ["A", "B", "D", "E"],
    "D": ["C", "E"],
    "E": ["C", "D"],
}
print(euler_type(bowtie), "cycle")

# несвязный граф из двух циклов - степени чётные, но граф не связен
disconnected = {0: [1], 1: [0], 2: [3], 3: [2]}
print(euler_type(disconnected), "none")

# изолированная вершина не мешает: треугольник (цикл) + вершина без рёбер
print(euler_type({0: [1, 2], 1: [0, 2], 2: [0, 1], 3: []}), "cycle")
